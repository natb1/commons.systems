/**
 * Port of the browser template's `mdBlocks`, adapted to keep a fenced
 * block's info string as `lang` so `renderProposal` can single out a
 * fenced ```markdown block -- a draft quoted into the account -- for its
 * own label; no other caller reads `lang`.
 *
 * @param {string} src
 * @returns {{type: string, lang?: string, html: string}[]}
 */
function alignBlocks(src) {
  const out = [];
  if (src == null || String(src).trim() === "") return out;
  const lines = String(src).replace(/\r\n?/g, "\n").split("\n");
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    const fence = line.match(/^\s*```(\S*)\s*$/);
    if (fence) {
      const code = [];
      i++;
      while (i < lines.length && !/^\s*```\s*$/.test(lines[i])) { code.push(lines[i]); i++; }
      i++;
      out.push({ type: "code", lang: fence[1] || "", html: `<pre><code>${alignEsc(code.join("\n"))}</code></pre>` });
      continue;
    }
    if (ALIGN_RE_RULE.test(line)) { out.push({ type: "rule", html: "<hr>" }); i++; continue; }
    const head = line.match(/^\s*(#{1,6})\s+(.*)$/);
    if (head) {
      const lvl = Math.max(3, Math.min(6, head[1].length));
      const text = head[2].trim().replace(/\s+#+\s*$/, "");
      out.push({ type: "heading", html: `<h${lvl}>${alignInline(text)}</h${lvl}>` });
      i++;
      continue;
    }
    if (/^\s*>/.test(line)) {
      const quoted = [];
      while (i < lines.length && /^\s*>/.test(lines[i])) { quoted.push(lines[i].replace(/^\s*>\s?/, "")); i++; }
      out.push({ type: "quote", html: `<blockquote>${alignHtml(quoted.join("\n"))}</blockquote>` });
      continue;
    }
    if (ALIGN_RE_BULLET.test(line) || ALIGN_RE_ORDER.test(line)) {
      const ordered = !ALIGN_RE_BULLET.test(line);
      const re = ordered ? ALIGN_RE_ORDER : ALIGN_RE_BULLET;
      const items = [];
      while (i < lines.length) {
        const m = lines[i].match(re);
        if (m) { items.push(m[2]); i++; }
        else if (items.length && lines[i].trim() && /^\s{2,}\S/.test(lines[i])) { items[items.length - 1] += ` ${lines[i].trim()}`; i++; }
        else break;
      }
      const tag = ordered ? "ol" : "ul";
      out.push({ type: "list", html: `<${tag}>${items.map((t) => `<li>${alignInline(t)}</li>`).join("")}</${tag}>` });
      continue;
    }
    const para = [];
    while (i < lines.length && lines[i].trim() && !ALIGN_RE_BREAK.test(lines[i]) && !ALIGN_RE_RULE.test(lines[i])) {
      para.push(lines[i].trim());
      i++;
    }
    if (!para.length) { i++; continue; }
    out.push({ type: "para", html: `<p>${alignInline(para.join(" "))}</p>` });
  }
  return out;
}

function alignHtml(src) {
  return alignBlocks(src).map((b) => b.html).join("");
}

/**
 * `## Account`, with a fenced ```markdown block -- a recommended text
 * quoted into the account -- called out in its own labelled block so it is
 * never mistaken for "The node as it stands" or for the node's own
 * `## Recommendation`.
 *
 * @param {string} src
 * @returns {string}
 */
function renderAccount(src) {
  return alignBlocks(src).map((b) => {
    if (b.type === "code" && b.lang === "markdown") {
      return `<div class="quoted"><p class="blk-label">Quoted in the account; the sections above are the node</p>${b.html}</div>`;
    }
    return b.html;
  }).join("");
}

// Doc ids may not contain '/'; a node id always does.
function alignDocId(nodeId) {
  return String(nodeId).replace(/\//g, ":");
}

function alignSection(label, bodyHtml, cls) {
  return `<section${cls ? ` class="${cls}"` : ""}><p class="lbl">${alignEsc(label)}</p><div class="mdbody">${bodyHtml}</div></section>`;
}

/* ------------------------------- the edit: node against its draft ---- */

// Every frontmatter key the reader carries except `question` (the
// validator already holds the draft to the node's own question) and the
// dialogue-state keys -- `stage`, `alternatives`, `recommendation`,
// `review`, `depends` -- which are the dialogue's own state, removed at the
// recording, and never part of what the author rules on.
const EDIT_FM_KEYS = [
  "form", "authority", "under", "tier", "boost", "cites", "instrument",
  "after", "source", "relation", "defines", "shims", "order",
];

// Key-sorted JSON, for comparison only: two values are the same field
// value when their canonical forms match, whatever order YAML gave the
// keys. `authority` is compared as a whole, as one value, because that is
// what a stamp is.
function stableJson(v) {
  if (v === null || v === undefined) return "null";
  if (Array.isArray(v)) return `[${v.map(stableJson).join(",")}]`;
  if (typeof v === "object") {
    return `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${stableJson(v[k])}`).join(",")}}`;
  }
  return JSON.stringify(v);
}

// YAML flow style, the compact one-line rendering of a frontmatter value:
// `rule`, `[a, b]`, `{class: ratified, by: claude, date: 2026-09-03}`, and
// `none` for an absent or empty one.
function flowYaml(v) {
  if (v === null || v === undefined) return "none";
  if (Array.isArray(v)) return v.length === 0 ? "none" : `[${v.map(flowYaml).join(", ")}]`;
  if (typeof v === "object") {
    const keys = Object.keys(v).filter((k) => v[k] !== null && v[k] !== undefined);
    if (keys.length === 0) return "none";
    return `{${keys.map((k) => `${k}: ${flowYaml(v[k])}`).join(", ")}}`;
  }
  return String(v);
}

/**
 * The frontmatter half of the edit: one entry per field whose value
 * differs between the node as it stands and its draft, in the reader's own
 * key order. The dialogue-state keys (see EDIT_FM_KEYS) are ignored.
 *
 * @param {object} node - a node as `read.mjs` returns it.
 * @param {{frontmatter: object}} draft - `node.draft`.
 * @returns {{field: string, before: string, after: string}[]}
 */
export function frontmatterEdits(node, draft) {
  const out = [];
  const fm = (draft && draft.frontmatter) || {};
  for (const key of EDIT_FM_KEYS) {
    const before = node[key] === undefined ? null : node[key];
    const after = fm[key] === undefined ? null : fm[key];
    if (stableJson(before) === stableJson(after)) continue;
    out.push({ field: key, before: flowYaml(before), after: flowYaml(after) });
  }
  return out;
}

const DIFF_TOKEN_CAP = 4000;

// A token is one run of non-whitespace plus the whitespace that followed
// it, normalized to a paragraph break or a single space, so the rendered
// diff keeps the text's paragraphs (the page sets `white-space: pre-wrap`
// on it) and reflows to the measure like every other body of prose on the
// page, whether or not the node's own file hard-wraps its lines. Only `t`
// is ever compared.
function diffTokens(text) {
  const out = [];
  const re = /(\S+)(\s*)/g;
  let m;
  const src = String(text == null ? "" : text);
  while ((m = re.exec(src)) !== null) {
    const ws = m[2] === "" ? "" : /\n[^\S\n]*\n/.test(m[2]) ? "\n\n" : " ";
    out.push({ t: m[1], ws });
  }
  return out;
}

// Longest common subsequence over two token lists, walked back into a flat
// op list. The table is filled from the end so the walk forward can be
// greedy, which keeps a run of insertions together rather than
// interleaving it with the deletions it replaces.
function lcsOps(a, b) {
  const n = a.length;
  const m = b.length;
  const w = m + 1;
  const dp = new Uint32Array((n + 1) * w);
  for (let i = n - 1; i >= 0; i -= 1) {
    for (let j = m - 1; j >= 0; j -= 1) {
      dp[i * w + j] = a[i].t === b[j].t
        ? dp[(i + 1) * w + (j + 1)] + 1
        : Math.max(dp[(i + 1) * w + j], dp[i * w + (j + 1)]);
    }
  }
  const ops = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i].t === b[j].t) { ops.push({ op: "same", tok: b[j] }); i += 1; j += 1; }
    else if (dp[(i + 1) * w + j] >= dp[i * w + (j + 1)]) { ops.push({ op: "del", tok: a[i] }); i += 1; }
    else { ops.push({ op: "ins", tok: b[j] }); j += 1; }
  }
  while (i < n) { ops.push({ op: "del", tok: a[i] }); i += 1; }
  while (j < m) { ops.push({ op: "ins", tok: b[j] }); j += 1; }
  return ops;
}

/**
 * A word-level diff of two section texts as a flat op list: `same` tokens
 * from the new text, `del` tokens from the old, `ins` tokens from the new.
 * The shared head and tail are matched off first, so the quadratic table
 * only ever covers what actually moved.
 *
 * Returns `null` -- the caller's cue to print the "too long to diff"
 * fallback -- when either side is longer than `cap` tokens, the one bound
 * on a table that is otherwise the product of the two lengths.
 *
 * @param {string|null} before
 * @param {string|null} after
 * @param {number} [cap]
 * @returns {{op: "same"|"del"|"ins", tok: {t: string, ws: string}}[]|null}
 */
export function wordDiff(before, after, cap = DIFF_TOKEN_CAP) {
  const a = diffTokens(before);
  const b = diffTokens(after);
  if (a.length > cap || b.length > cap) return null;
  let head = 0;
  while (head < a.length && head < b.length && a[head].t === b[head].t) head += 1;
  let tail = 0;
  while (
    tail < a.length - head
    && tail < b.length - head
    && a[a.length - 1 - tail].t === b[b.length - 1 - tail].t
  ) tail += 1;
  const ops = b.slice(0, head).map((tok) => ({ op: "same", tok }));
  ops.push(...lcsOps(a.slice(head, a.length - tail), b.slice(head, b.length - tail)));
  ops.push(...b.slice(b.length - tail).map((tok) => ({ op: "same", tok })));
  return ops;
}

// Consecutive ops of one kind become one <ins>/<del>; the run's own
// trailing whitespace is emitted outside the tag, so a struck-through or
// underlined run never swallows the space or newline after it.
function diffHtml(ops) {
  let html = "";
  let i = 0;
  while (i < ops.length) {
    const kind = ops[i].op;
    const run = [];
    while (i < ops.length && ops[i].op === kind) { run.push(ops[i].tok); i += 1; }
    const inner = run.map((tok, k) => alignEsc(tok.t) + (k < run.length - 1 ? tok.ws : "")).join("");
    const trailing = run[run.length - 1].ws;
    if (kind === "same") html += inner + trailing;
    else if (kind === "ins") html += `<ins>${inner}</ins>${trailing}`;
    else html += `<del>${inner}</del>${trailing}`;
  }
  return html;
}

function renderSectionDiff(label, before, after) {
  if (!(before || "").trim() && !(after || "").trim()) return "";
  const ops = wordDiff(before, after);
  const body = ops === null
    ? '<p class="none">Too long to diff: read the draft above against the node as it stands.</p>'
    : `<div class="diff">${diffHtml(ops)}</div>`;
  return `<p class="difflbl">${alignEsc(label)}</p>${body}`;
}

/* --------------------------------------------- the alternatives ----- */

/**
 * The divergence inversion for one alternative `alternativeName` of node
 * `n`: every other node's `depends` entry that names `n` is, on the leaf,
 * a decision the leaf stands under; here, on the ancestor, it is inverted
 * into what a ruling for this alternative would do. `keeps` is every node
 * whose `depends` entry names `n` under exactly this alternative -- a
 * ruling for it leaves that leaf's ground as recorded; `discards` is every
 * node whose `depends` entry names `n` under some other named alternative
 * -- a ruling for this one contradicts what that leaf stood under. Neither
 * list ever includes a plain, unqualified `depends` entry (an open
 * question waiting on `n`'s ruling generally, not a stand taken under one
 * particular alternative). Both sorted ascending; this is derived fresh
 * from the graph each time, never stored on the record.
 *
 * @param {{id: string}} n
 * @param {string} alternativeName
 * @param {object[]} allNodes - the full node list, `graph.nodes`.
 * @returns {{keeps: string[], discards: string[]}}
 */
function divergenceFor(n, alternativeName, allNodes) {
  const keeps = [];
  const discards = [];
  for (const other of allNodes) {
    for (const d of other.depends || []) {
      if (d.id !== n.id || d.alternative == null) continue;
      if (d.alternative === alternativeName) keeps.push(other.id);
      else discards.push(other.id);
    }
  }
  return { keeps: keeps.sort(), discards: discards.sort() };
}

// The one extra paragraph a divergence adds to an alternative's block (see
// renderDecision): what a ruling for this alternative keeps of the
// leaves standing under it, and, unless there are none, what it discards
// of the leaves standing under a different alternative of the same node.
function renderDivergenceParagraph(keeps, discards) {
  if (keeps.length === 0) {
    return `<p class="divergence">${alignEsc("A ruling for this keeps nothing recorded.")}</p>`;
  }
  let html = `<p class="divergence">A ruling for this keeps: <em>${keeps.map(alignEsc).join(", ")}</em>.`;
  if (discards.length > 0) {
    html += ` It discards: <em>${discards.map(alignEsc).join(", ")}</em>.`;
  }
  return `${html}</p>`;
}

// What the recommendation itself carries, beneath the node it proposes: the
// alternative it adopts, its boldness, whether its pin has gone stale under
// it, and the persistence a confirmation would leave. It carries no class:
// the class a confirmation confers is the `authority` fact
// (commons.systems/disposition-graph/dialogue).
function renderRecommendation(n) {
  if (!n.recommendation) {
    return '<p class="recline none">No recommendation yet.</p>';
  }
  const rec = n.recommendation;
  let pills = `<span class="pill rec-adopts">adopts: ${alignEsc(rec.adopts)}</span>`
    + `<span class="pill rec-bold-${alignEsc(rec.boldness)}">boldness: ${alignEsc(rec.boldness)}</span>`;
  if (n.recommendationStale) {
    pills += '<span class="pill rec-stale">standing text changed since the recommendation</span>';
  }
  const shims = persistenceShims(n);
  const persistence = shims.length === 0
    ? '<p class="persist">Persistence: standing.</p>'
    : `<p class="persist">Persistence: standing, with ${shims.length} shim${shims.length === 1 ? "" : "s"}:</p>`
      + `<ul class="shims">${shims.map((s) => `<li>${alignInline(s.artifact)}</li>`).join("")}</ul>`;
  return `<p class="pills recline">${pills}</p>${persistence}`;
}

/**
 * "The alternatives": every answer on the table beside the one the node
 * stands on, in the `alternatives` list's own order, each with its name,
 * where it came from (`source`, and the `ref` that dates it or names the
 * instrument that raised it) and its prose from the `## Alternatives`
 * subsection of the same name. The one the recommendation adopts is
 * marked, and so is one that would prune the node rather than rewrite it.
 *
 * When at least one of the node's alternatives has a leaf standing under it
 * (a `depends` entry naming this node with that alternative), every
 * alternative's block gets one extra paragraph inverting that: what a
 * ruling for it keeps, and, when there is at least one, what it discards
 * of the leaves standing under a sibling alternative instead (see
 * `divergenceFor`). An alternative untouched by any leaf still gets the
 * paragraph in that case, saying so plainly, since that is itself the fact
 * a ruling for it would need: nothing is recorded as depending on it.
 *
 * Nothing is rendered for a node with no alternatives: an empty section on
 * every other item would be noise on a page the author reads top to bottom.
 *
 * @param {object} n - a node as `read.mjs` returns it.
 * @param {object[]} allNodes - the full node list, `graph.nodes`, for the
 *   divergence inversion.
 * @returns {string}
 */
/* ------------------------- the recommendation and the review --------- */

// The shims a confirmation would leave standing: the draft's when the node
// has one that declares any, the node's own otherwise.
function persistenceShims(n) {
  const draftShims = n.draft && n.draft.frontmatter ? n.draft.frontmatter.shims : null;
  if (Array.isArray(draftShims) && draftShims.length > 0) return draftShims;
  return Array.isArray(n.shims) ? n.shims : [];
}

function renderReview(n) {
  if (!n.review) {
    return '<section class="rev"><p class="lbl">The review</p><p class="none">Not yet reviewed.</p></section>';
  }
  const verdict = n.review.verdict === "forward" ? "forwarded" : "kicked back";
  let pills = `<span class="pill rev-${alignEsc(n.review.verdict)}">${alignEsc(verdict)}</span>`
    + `<span class="pill rev-strength">counter-argument: ${alignEsc(n.review.strength)}</span>`
    + `<span class="pill rev-date">${alignEsc(n.review.date)}</span>`;
  if (n.reviewStale) pills += '<span class="pill rev-stale">draft changed since the review</span>';
  return `<section class="rev"><p class="lbl">The review</p><p class="pills">${pills}</p></section>`;
}

/* --------------------------- the ruling screen ------------------------
 *
 * commons.systems/disposition-graph/alignment-page: one node at a time, on
 * a three-column screen, in the ruling order. The rail carries the metrics
 * and every unanswered node; the middle column carries the decisions this
 * ruling asks; the right-hand column carries the node as it would stand,
 * with its unanswered children beneath it as indications and never as rows.
 */

// The browser's published address, read out of the record rather than
// written here: the shim that names it is declared on
// commons.systems/disposition-graph/projection. A metric links to the
// disposition it instruments at that address, since this page addresses no
// node of its own. Null when no shim names it, and then a metric renders
// unlinked rather than pointing nowhere.
function browserAddress(graph) {
  for (const n of graph.nodes || []) {
    for (const s of n.shims || []) {
      const text = String(s.artifact || "");
      if (!/browser/i.test(text)) continue;
      const m = text.match(/https:\/\/\S*?artifact\/[0-9a-f-]+/i);
      if (m) return m[0];
    }
  }
  return null;
}

// The four metrics, each a signal of a recorded disposition and never a
// count for its own sake, as this page's answer requires. `of` names the
// node the metric instruments; the rail links to it.
function alignmentMetrics(items) {
  const first = items[0] || null;
  return [
    {
      key: "open",
      value: items.length,
      of: "commons.systems/disposition-graph/unanswered",
      why: "Nodes the author has not confirmed. Every node is unanswered until they do, so this is the outstanding authority.",
    },
    {
      key: "ruleable",
      value: items.filter((n) => n.stage === "ruling").length,
      of: "commons.systems/disposition-graph/clean-context-review",
      why: "Nodes whose clean-context review is behind them. The review is what stands between a draft and the author, so this is what can be ruled now.",
    },
    {
      key: "next settles",
      value: first && typeof first.settles === "number" ? first.settles : 0,
      of: "commons.systems/disposition-graph/alignment-order",
      why: "What a ruling on the first node in the order would make decidable. The order puts the ruling that settles the most first, so this is what one ruling buys.",
    },
    {
      key: "stale",
      value: items.filter((n) => n.recommendationStale || n.reviewStale).length,
      of: "commons.systems/disposition-graph/frontier-consistency",
      why: "Nodes whose recommendation or review pin no longer matches the text it read. This is how much of what looks ruleable rests on a reading of text that has moved.",
    },
  ];
}

function renderMetrics(items, browser) {
  const cells = alignmentMetrics(items).map((m) => {
    const inner = `<dt>${alignEsc(m.key)}</dt><dd class="num">${alignEsc(m.value)}</dd>`;
    const title = `${m.why} Instruments ${m.of}.`;
    return browser === null
      ? `<div class="metric" title="${alignEsc(title)}">${inner}</div>`
      : `<a class="metric" href="${alignEsc(browser)}#${alignEsc(m.of)}" target="_blank" rel="noopener" title="${alignEsc(title)}">${inner}</a>`;
  }).join("");
  return `<dl class="metrics">${cells}</dl>`;
}

/* ------------------------- the decisions this ruling asks ------------- */

// The decisions a ruling on this node asks: its own answer, where
// alternatives are pending on it, and its asking facts. A decision is asked
// whenever its boldness is anything but low and folds unasked into the
// right-hand column when its boldness is low -- and because boldness runs
// from the AI's own knowledge against the record, high boldness is low
// confidence, so the fold is on `low` and never on `high`.
function decisionsFor(n, allNodes) {
  const out = [];
  const alts = Array.isArray(n.alternatives) ? n.alternatives : [];
  const rec = n.recommendation || null;
  if (alts.length > 0) {
    const text = n.alternativesText || {};
    const divergences = alts.map((a) => divergenceFor(n, a.name, allNodes));
    const showDivergence = divergences.some((d) => d.keeps.length > 0);
    const choices = [
      {
        value: STANDING_CHOICE,
        label: STANDING_CHOICE,
        pills: [{ cls: "alt-src", text: "the node as it stands" }],
        prose: "",
        divergence: "",
      },
      ...alts.map((a, i) => ({
        value: a.name,
        label: a.name,
        pills: [
          { cls: "alt-src", text: a.source },
          ...(a.ref ? [{ cls: "alt-ref mono", text: a.ref }] : []),
        ],
        prose: text[a.name] || "",
        divergence: showDivergence
          ? renderDivergenceParagraph(divergences[i].keeps, divergences[i].discards)
          : "",
      })),
    ];
    out.push({
      name: "answer",
      label: "The answer",
      // With no recommendation yet there is no boldness to fold on, and a
      // decision nobody has recommended is asked, never folded away.
      boldness: rec ? rec.boldness : null,
      adopts: rec ? rec.adopts : null,
      choices,
    });
  }
  const factText = n.factsText || {};
  for (const f of n.facts || []) {
    out.push({
      name: f.name,
      label: FACT_LABELS[f.name] || f.name,
      boldness: f.boldness,
      adopts: f.adopts,
      ruling: f.ruling || null,
      // The '## Facts' subsection explains the fact's choices as a set, so
      // it sits under the legend and not on any one row.
      prose: factText[f.name] || "",
      choices: f.choices.map((c) => ({
        value: c, label: c, pills: [], prose: "", divergence: "",
      })),
    });
  }
  return out;
}

function renderDecision(doc, d) {
  const rows = d.choices.map((c) => {
    const adopted = c.value === d.adopts;
    const pills = c.pills.map((p) => `<span class="pill ${p.cls}">${alignEsc(p.text)}</span>`).join("")
      + (adopted ? `<span class="pill alt-adopted">${alignEsc(ADOPTED_MARK)}</span>` : "");
    const drill = c.prose || c.divergence
      ? `<details class="drill"><summary>What this would answer</summary>`
        + (c.prose ? `<div class="mdbody">${alignHtml(c.prose)}</div>` : "")
        + c.divergence
        + "</details>"
      : "";
    return `<li class="choice${adopted ? " adopted" : ""}">`
      + `<label class="choicelbl"><input type="radio" name="dec:${alignEsc(doc)}:${alignEsc(d.name)}" value="${alignEsc(c.value)}" data-choice>`
      + `<span class="choicename mono">${alignEsc(c.label)}</span></label>${pills}${drill}</li>`;
  }).join("");
  const reject = `<li class="choice reject">`
    + `<label class="choicelbl"><input type="radio" name="dec:${alignEsc(doc)}:${alignEsc(d.name)}" value="${alignEsc(REJECT_CHOICE)}" data-choice>`
    + `<span class="choicename">${alignEsc(REJECT_LABEL)}</span></label></li>`;
  const ruled = d.ruling
    ? `<p class="ruled">Ruled ${alignEsc(d.ruling.response)} on <span class="mono">${alignEsc(d.ruling.choice)}</span>, ${alignEsc(d.ruling.date)}.</p>`
    : "";
  const why = d.prose ? `<div class="mdbody decwhy">${alignHtml(d.prose)}</div>` : "";
  const bold = d.boldness
    ? `<span class="pill rec-bold-${alignEsc(d.boldness)}">boldness: ${alignEsc(d.boldness)}</span>`
    : '<span class="pill rec-bold-none">no recommendation yet</span>';
  return `<fieldset class="decision" data-decision="${alignEsc(d.name)}">`
    + `<legend class="declbl">${alignEsc(d.label)}${bold}</legend>`
    + ruled
    + why
    + `<ul class="choices">${rows}${reject}</ul>`
    + `<textarea class="note dec-note" data-decision-text rows="2" placeholder="${alignEsc(DECISION_NOTE_PLACEHOLDER)}" hidden></textarea>`
    + "</fieldset>";
}

function renderDecisions(n, allNodes) {
  const doc = alignDocId(n.id);
  const decisions = decisionsFor(n, allNodes);
  const asked = decisions.filter((d) => d.boldness !== "low");
  const folded = decisions.filter((d) => d.boldness === "low");
  const body = asked.length === 0
    ? `<p class="none">${alignEsc(NOTHING_ASKED)}</p>`
    : asked.map((d) => renderDecision(doc, d)).join("");
  const foldline = folded.length === 0
    ? ""
    : `<p class="folded">${alignEsc(FOLDED_LEAD)} `
      + folded.map((d) => `<span class="mono">${alignEsc(d.label)}: ${alignEsc(d.adopts)}</span>`).join(", ")
      + ".</p>";
  return `<section class="decisions"><p class="lbl">${alignEsc(DECISIONS_LBL)}</p>${body}${foldline}</section>`;
}

/* ------------------------- the node as it would stand ----------------- */

// The unanswered children of this node, and the open questions that name it
// in `depends`: indications of what a ruling here makes decidable, shown
// beneath the node and never as rows to rule from, since every node is
// ruled from the rail in its own turn in the one order.
function paneIndications(n, allNodes) {
  const children = allNodes
    .filter((o) => o.stage && (o.under || []).includes(n.id))
    .map((o) => ({ id: o.id, question: o.question, how: "under it" }));
  const waiting = allNodes
    .filter((o) => o.stage && (o.depends || []).some((d) => d.id === n.id))
    .map((o) => ({
      id: o.id,
      question: o.question,
      how: (o.depends.find((d) => d.id === n.id).alternative
        ? `waits on ${o.depends.find((d) => d.id === n.id).alternative}`
        : "waits on this ruling"),
    }));
  const seen = new Set();
  const all = [...children, ...waiting].filter((x) => (seen.has(x.id) ? false : seen.add(x.id)));
  if (all.length === 0) return "";
  const items = all.map((x) => (
    `<li><span class="indq">${alignEsc(x.question || x.id)}</span>`
    + `<span class="meta mono">${alignEsc(x.how)}</span>`
    + `<span class="indid mono">${alignEsc(x.id)}</span></li>`
  )).join("");
  return `<section class="indications"><p class="lbl">${alignEsc(INDICATIONS_LBL)} (${all.length})</p>`
    + `<p class="hint">${alignEsc(INDICATIONS_HINT)}</p><ul class="indlist">${items}</ul></section>`;
}

function renderPane(n, allNodes) {
  const doc = alignDocId(n.id);
  const hasAnswer = typeof n.answer === "string" && n.answer.length > 0;
  const stamped = n.authority !== null && n.authority !== undefined;
  let body;
  let caption;
  if (n.draft) {
    const d = n.draft;
    const whole = `<div class="mdbody">${alignHtml(d.sections.Answer)}${alignHtml(d.sections.Rationale)}</div>`;
    if (stamped) {
      const fm = frontmatterEdits(n, d);
      const fmHtml = fm.length === 0
        ? '<p class="none">No frontmatter field changes.</p>'
        : `<ul class="fmdiff">${fm.map((e) => `<li><code>${alignEsc(e.field)}</code>: <span class="was">${alignEsc(e.before)}</span> <span class="arrow">&rarr;</span> <span class="now">${alignEsc(e.after)}</span></li>`).join("")}</ul>`;
      const diffs = renderSectionDiff("Answer", n.answer, d.sections.Answer)
        + renderSectionDiff("Rationale", n.rationale, d.sections.Rationale);
      body = `<p class="lbl edit-lbl">The edit</p><div class="edit">${fmHtml}${diffs}</div>`
        + `<p class="lbl edit-lbl">The node it would leave</p>${whole}`;
      caption = EDIT_CAPTION;
    } else {
      body = whole;
      caption = FIRST_ANSWER_CAPTION;
    }
  } else if (hasAnswer) {
    body = `<div class="mdbody">${alignHtml(n.answer)}${n.rationale ? alignHtml(n.rationale) : ""}</div>`;
    caption = stamped ? STANDING_CAPTION : FIRST_ANSWER_CAPTION;
  } else {
    body = `<p class="none">${alignEsc(NO_ANSWER_LINE)}</p>`;
    caption = OPEN_QUESTION_CAPTION;
  }
  const words = n.disposition
    ? `<details class="drill words"><summary>The author's words</summary><div class="mdbody">${alignHtml(n.disposition)}</div></details>`
    : "";
  const account = n.account
    ? `<details class="drill"><summary>The AI's account</summary><div class="mdbody">${renderAccount(n.account)}</div></details>`
    : "";
  return '<aside class="col-pane">'
    + `<section class="stands"><p class="lbl">${alignEsc(PANE_LBL)}</p>${body}`
    + `<p class="caption">${alignEsc(caption)}</p>${renderRecommendation(n)}</section>`
    // Beneath the node, what a ruling here makes decidable; then the
    // review's reading of it, the author's words and the AI's account as
    // drill-downs; then the rejection of the whole, last
    // (commons.systems/disposition-graph/alignment-page).
    + paneIndications(n, allNodes)
    + renderReview(n)
    + words
    + account
    + renderWholeResponse(n, doc)
    + "</aside>";
}

// The whole-node response, beneath the node as it would stand: the three
// responses the unanswered node opens, and this page adds none.
function renderWholeResponse(n, doc) {
  const hint = STAGE_HINT[n.stage];
  const placeholder = n.stage === "periagogic" || n.stage === "maieutic" ? WORDS_PLACEHOLDER : "";
  const opts = RESPONSE_CHOICES.map((c) => (
    `<label class="segopt"><input type="radio" name="opt:${alignEsc(doc)}" value="${alignEsc(c.value)}" data-option data-note-label="${alignEsc(c.note)}"><span>${alignEsc(c.label)}</span></label>`
  )).join("");
  return '<div class="response">'
    + (hint ? `<p class="hint">${alignEsc(hint)}</p>` : "")
    + '<fieldset class="controls" data-controls>'
    + `<legend class="lbl">${alignEsc(WHOLE_RESPONSE_LBL)}</legend>`
    + `<div class="seg">${opts}</div>`
    + `<label class="note-lbl" data-note-lbl for="note-${alignEsc(doc)}">A note, edits, or feedback</label>`
    + `<textarea class="note" id="note-${alignEsc(doc)}" data-field="text" rows="3"${placeholder ? ` placeholder="${alignEsc(placeholder)}"` : ""}></textarea>`
    + "</fieldset>"
    + '<p class="state" data-state hidden></p>'
    + "</div>";
}

function renderAlignmentItem(n, allNodes) {
  const under = n.under || [];
  const doc = alignDocId(n.id);
  const stamp = n.authority
    ? `${n.authority.class} · ${n.authority.by} · ${n.authority.date}`
    : "no stamp";
  const rank = typeof n.rank === "number" ? n.rank.toFixed(4) : "—";

  let html = `<article class="item" id="item-${alignEsc(doc)}" data-item data-id="${alignEsc(n.id)}" data-doc="${alignEsc(doc)}" data-stage="${alignEsc(n.stage)}" hidden>`;
  html += '<div class="col-ask">';
  html += `<h2 class="iq">${alignEsc(n.question || n.id)}</h2>`;
  html += `<p class="idv mono">${alignEsc(n.id)}</p>`;
  html += '<p class="eyebrow">'
    + `<span class="pill stage-${alignEsc(n.stage)}">${alignEsc(n.stage)}</span>`
    + `<span class="meta mono">${alignEsc(n.graph)}</span>`
    + (typeof n.settles === "number" ? `<span class="meta mono num">settles ${alignEsc(n.settles)}</span>` : "")
    // The alternatives pending on a node are shown beside its settling
    // count: they are what tells the author what a sitting will cost, and
    // they order nothing (commons.systems/disposition-graph/alignment-order).
    + (n.alternatives && n.alternatives.length > 0
      ? `<span class="meta mono num">${alignEsc(n.alternatives.length)} alternative${n.alternatives.length === 1 ? "" : "s"}</span>`
      : "")
    + `<span class="meta mono num">rank ${alignEsc(rank)}</span>`
    + `<span class="meta mono">${alignEsc(stamp)}</span>`
    + `<span class="meta mono parents">${under.length ? `under ${alignEsc(under.join(", "))}` : "a root"}</span>`
    + "</p>";
  html += renderDecisions(n, allNodes);
  html += "</div>";
  html += renderPane(n, allNodes);
  html += "</article>";
  return html;
}

/**
 * Every node carrying a `stage`, in one flat ruling order across every
 * graph the manifest names: `settles` descending, then `rank` descending,
 * then id. The alignment frontier's dependencies cross graphs --
 * `commons.systems/public/agency` is the sole root and every
 * `disposition-graph` node hangs under it -- so a graph is a label on a
 * node here, never a precedence; ordering graph by graph would put a
 * descendant's ruling ahead of its own ancestor's, exactly what the ruling
 * order exists to prevent.
 *
 * `graphs` lists every declared graph in the manifest's own order, its
 * `about` text, and how many of `items` belong to it, with a graph a node
 * names but the manifest does not declare appended after the declared ones
 * rather than dropped, so no open dialogue's graph can go missing. The page
 * renders only the label, on each rail row: the pagehead that carried the
 * `about` lines and the per-stage counts liquidated without a disposition,
 * on the author's ruling of 2026-09-03
 * (commons.systems/disposition-graph/alignment-page).
 *
 * @param {{graphs?: object, nodes?: object[]}} graph
 * @returns {{items: object[], graphs: {graph: string, label: string, about: string|null, count: number}[]}}
 */
export function orderAlignmentItems(graph) {
  const items = (graph.nodes || []).filter((n) => n.stage).sort((a, b) => {
    const bs = b.settles ?? 0;
    const as = a.settles ?? 0;
    if (bs !== as) return bs - as;
    return b.rank !== a.rank ? b.rank - a.rank : (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  });

  const declared = graph.graphs && typeof graph.graphs === "object" ? Object.keys(graph.graphs) : [];
  const names = [...declared];
  for (const n of items) if (!names.includes(n.graph)) names.push(n.graph);

  const graphs = names.map((name) => {
    const entry = (graph.graphs && graph.graphs[name]) || {};
    return {
      graph: name,
      label: name,
      about: typeof entry.about === "string" ? entry.about : null,
      count: items.filter((n) => n.graph === name).length,
    };
  });

  return { items, graphs };
}

function alignmentPageHtml(graph, items, graphs) {
  const total = items.length;
  const browser = browserAddress(graph);
  const graphOf = new Map(graphs.map((g) => [g.graph, g.label]));

  // The rail is the only view of the whole frontier once one node is shown
  // at a time, which is why the metrics sit at its top and why it lists
  // every node, filtering and paging nothing.
  const railHtml = `<ol class="tree">${items.map((n, i) => {
    const doc = alignDocId(n.id);
    const settles = typeof n.settles === "number" ? n.settles : 0;
    return `<li><a href="#item-${alignEsc(doc)}" data-rail data-doc="${alignEsc(doc)}" aria-current="false">`
      + `<span class="dot stage-${alignEsc(n.stage)}" aria-hidden="true"></span>`
      + `<span class="rq">${alignEsc(n.question || n.id)}</span>`
      + `<span class="rmeta mono">${alignEsc(i + 1)} · settles ${alignEsc(settles)}`
      + ` · ${alignEsc(graphOf.get(n.graph) || n.graph)}</span>`
      + '<span class="mark" data-mark></span></a></li>';
  }).join("")}</ol>`;

  const itemsHtml = items.map((n) => renderAlignmentItem(n, graph.nodes)).join("");

  const emptyHtml = total === 0
    ? '<p class="empty">Nothing is unanswered. Every disposition has been confirmed by the author.</p>'
    : "";
  const refline = alignEsc([graph.module, graph.ref].filter(Boolean).join(" · "));

  return `<header class="mast">
  <div class="mast-in">
    <div class="brand">
      <span class="wordmark">Alignment</span>
      <span class="refline">${refline}</span>
      <span id="module-name" hidden>${alignEsc(graph.module || "")}</span>
    </div>
    <nav class="tools" aria-label="Actions">
      <button type="button" class="tbtn" id="btn-wide" aria-pressed="false">Widen the node</button>
      <button type="button" class="tbtn" id="btn-copy">Copy all responses</button>
      <button type="button" class="tbtn" id="btn-theme">Theme: auto</button>
    </nav>
  </div>
</header>
<div class="shell">
  <nav class="nav" id="nav" aria-label="The unanswered frontier, in the ruling order">
    ${renderMetrics(items, browser)}
    <div id="tree">${railHtml}</div>
  </nav>
  <main id="main">
    <p class="notice" id="notice" hidden></p>
    ${itemsHtml}
    ${emptyHtml}
  </main>
</div>
<footer class="foot" id="foot">
  <div class="foot-in">
    <span class="foot-count" id="staged-count">0 responses staged</span>
    <span class="foot-note" id="foot-note"></span>
    <button type="button" class="sbtn" id="btn-submit" disabled>Submit 0 responses</button>
  </div>
</footer>`;
}

/**
 * Render every node carrying a `stage` into
 * `packages/disposition/alignment-template.html`: the open dialogue the
 * author rules on, one flat page, in one ruling order across every graph
 * (see `orderAlignmentItems`). See the section comment above for why this
 * renders to HTML in Node rather than inlining JSON for a client-side
 * router, unlike `build()`.
 *
 * @param {string} template
 * @param {{module?: string, ref?: string|null, graphs?: object, nodes: object[]}} graph
 * @returns {string}
 */
export function buildAlignment(template, graph) {
  if (!template.includes(ALIGNMENT_MARKER)) throw new Error(`template has no ${ALIGNMENT_MARKER} marker`);
  const { items, graphs } = orderAlignmentItems(graph);
  const block = alignmentPageHtml(graph, items, graphs);
  return template.replace(ALIGNMENT_MARKER, () => block);
}

// Builds the browser page only when opts.out is given -- --rules and
// --ancestry are independent outputs that do not need it (see writeRules,
// writeAncestry), and check() only makes sense against the page's contract.
// check() runs against the full graph; excludeUnaligned() is applied only to
// what build() actually receives (see excludeUnaligned's own doc comment).
export async function project(opts) {
  const graph = await loadGraph(opts);
  if (!opts.out) return { out: null, html: null, graph, warnings: [] };
  const warnings = check(graph);
  const template = await readFile(resolve(HERE, "browser-template.html"), "utf8");
  const html = build(template, excludeUnaligned(graph));
  const out = resolve(opts.out);
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, html);
  return { out, html, graph, warnings };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const opts = parseArgs(process.argv.slice(2));
  await runCli(opts);
}

// `readGraph` either returns a fully valid graph or throws with every
// problem it found and no partial data at all -- there is no "graph, plus
// a list of what's wrong with it" to render around. Rendering the frontier
// or the browser anyway on a graph that fails validation would need that
// contract to change everywhere `readGraph` is read from (validate.mjs,
// every output here, every test), which is a larger change than this
// unit's dialogue rules; the CLI's obligation ends at reporting that it
// cannot, cleanly, in the reader's own per-line message style, rather than
// an uncaught exception's raw stack trace.
async function runCli(opts) {
  let out, html, graph, warnings;
  try {
    ({ out, html, graph, warnings } = await project(opts));
  } catch (err) {
    process.stderr.write(`${err.message}\n`);
    process.exitCode = 1;
    return;
  }

  if (opts.rules) {
    const result = await writeRules(graph, opts.rules);
    for (const f of result.written) process.stdout.write(`wrote ${f}\n`);
    for (const f of result.deleted) process.stdout.write(`deleted ${f}\n`);
  }

  if (opts.ancestry) {
    const result = await writeAncestry(graph, opts.ancestry, opts.local);
    process.stdout.write(`wrote ${result.file}\n`);
  }

  if (opts.frontier) {
    const listing = renderFrontier(graph);
    if (opts.frontier === "-") {
      process.stdout.write(listing);
    } else {
      const filePath = resolve(opts.frontier);
      await mkdir(dirname(filePath), { recursive: true });
      await writeFile(filePath, listing);
      process.stdout.write(`wrote ${filePath}\n`);
    }
  }

  if (opts.alignment) {
    const alignmentTemplate = await readFile(resolve(HERE, "alignment-template.html"), "utf8");
    const alignmentHtml = buildAlignment(alignmentTemplate, graph);
    if (opts.alignment === "-") {
      process.stdout.write(alignmentHtml);
    } else {
      const filePath = resolve(opts.alignment);
      await mkdir(dirname(filePath), { recursive: true });
      await writeFile(filePath, alignmentHtml);
      process.stdout.write(`wrote ${filePath} (${Buffer.byteLength(alignmentHtml)} bytes)\n`);
    }
  }

  if (out) {
    for (const w of warnings) process.stderr.write(`contract: ${w}\n`);
    process.stdout.write(
      `${graph.nodes.length} nodes, ${Object.keys(graph.graphs).length} graphs -> ${out} (${Buffer.byteLength(html)} bytes)\n`
    );
  }

  if (!out && !opts.rules && !opts.ancestry && !opts.frontier && !opts.alignment) {
    process.stderr.write("nothing to do: pass --out, --rules, --ancestry (with --local), --frontier, or --alignment\n");
    process.exitCode = 1;
  }
}
